from pack_model import ATTRIBUTION  # noqa: E402

EMS_CREDIT = "European Union, Copernicus Emergency Management Service data"
AGREE_COLORS = ["#eeeeee", "#38a169", "#e53e3e", "#2b6cb0"]       # dry, agree flood, ours only, reference only


def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    return plt


# =============================================================================
# 1. MANIFEST + SAVING
# =============================================================================
class FigureManifest:
    """figures_manifest.json: for every figure we made - file name, SHA-256,
    caption, which data it shows, creation time.

    TRICK T8 (provenance for the "no victim images" rule):
        audit.py lists every image file in the report folders; any image NOT in
        this manifest was not generated by our code and is flagged for a human to
        look at ("is this a photo of people?").  So the rule is enforced by
        construction for our own figures and by a visible warning for the rest.
    """

    def __init__(self, path):
        self.path = Path(path)
        self.items: Dict[str, Dict] = {}
        if self.path.exists():
            self.items = json.loads(self.path.read_text()).get("figures", {})

    def add(self, fig_path: Path, caption: str, uses_ems: bool) -> None:
        self.items[fig_path.name] = {"sha256": hashlib.sha256(fig_path.read_bytes()).hexdigest(),
                                     "caption": caption, "uses_ems_reference": uses_ems,
                                     "created": time.strftime("%Y-%m-%d %H:%M:%S")}
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps({"figures": self.items}, indent=2))


def save_figure(fig, path, manifest: FigureManifest, caption: str, uses_ems: bool = False,
                show_sentinel: bool = True, show_osm: bool = False) -> Path:
    """Stamp the REQUIRED attribution on the figure, save it, record it.

    TRICK T9 (attribution cannot be forgotten): the required lines are written
    onto the picture itself at save time (Sentinel always; OSM when the figure
    shows OpenStreetMap data; the EMS credit when it shows the EMSR927
    reference).  A figure copied into slides keeps its credit.
    """
    parts: List[str] = []
    if show_sentinel:
        parts.append(ATTRIBUTION[0])
    if show_osm:
        parts.append(ATTRIBUTION[2])
    if uses_ems:
        parts.append(f"Reference: {EMS_CREDIT} (EMSR927), used for checking only.")
    # one line per credit: a long single line would be cut off on narrow figures
    fig.text(0.5, 0.005, "\n".join(parts), ha="center", va="bottom", fontsize=6.5, color="#444444")
    fig.subplots_adjust(bottom=0.1 + 0.035 * len(parts))
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130)
    _plt().close(fig)
    manifest.add(path, caption, uses_ems)
    return path


