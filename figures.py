def _stretch(a: np.ndarray, lo: float = 2, hi: float = 98) -> np.ndarray:
    v = a[np.isfinite(a)]
    if v.size == 0:
        return np.zeros_like(a)
    p0, p1 = np.percentile(v, [lo, hi])
    return np.clip((np.nan_to_num(a, nan=p0) - p0) / max(p1 - p0, 1e-6), 0, 1)


def fig_before_after(before_vv: np.ndarray, after_vv: np.ndarray):
    """F1: radar BEFORE and AFTER side by side (same display stretch for both,
    so a brightness difference between them is real, not a display artefact)."""
    plt = _plt()
    both = np.concatenate([before_vv[np.isfinite(before_vv)], after_vv[np.isfinite(after_vv)]])
    p0, p1 = np.percentile(both, [2, 98])
    fig, ax = plt.subplots(1, 2, figsize=(10, 4.6))
    for a, img, t in ((ax[0], before_vv, "BEFORE (Sentinel-1 VV)"), (ax[1], after_vv, "AFTER (Sentinel-1 VV)")):
        a.imshow(np.clip((np.nan_to_num(img, nan=p0) - p0) / (p1 - p0), 0, 1), cmap="gray")
        a.set_title(t, fontsize=10)
        a.axis("off")
    return fig


def fig_overlay(after_vv: np.ndarray, mask: np.ndarray, confidence: Optional[np.ndarray] = None):
    """F2: our flood mask drawn over the AFTER image (and the confidence map)."""
    plt = _plt()
    n = 2 if confidence is not None else 1
    fig, ax = plt.subplots(1, n, figsize=(5.2 * n, 4.6), squeeze=False)
    base = _stretch(after_vv)
    rgb = np.stack([base] * 3, axis=-1)
    flood = mask == 1
    rgb[flood] = 0.45 * rgb[flood] + 0.55 * np.array([0.9, 0.15, 0.15])
    rgb[mask == 255] = 0.0
    ax[0, 0].imshow(rgb); ax[0, 0].set_title("Predicted flood (red)", fontsize=10); ax[0, 0].axis("off")
    if confidence is not None:
        im = ax[0, 1].imshow(confidence, cmap="viridis", vmin=0, vmax=1)
        ax[0, 1].set_title("Model confidence P(flood)", fontsize=10); ax[0, 1].axis("off")
        fig.colorbar(im, ax=ax[0, 1], fraction=0.046, pad=0.02)
    return fig


def fig_agreement(agreement: np.ndarray, iou: Optional[float] = None):
    """F3: ours vs the EMSR927 reference. green = both flood, red = ours only,
    blue = reference only, grey = both dry, white = not compared."""
    plt = _plt()
    from matplotlib.colors import ListedColormap
    from matplotlib.patches import Patch
    show = np.where(agreement == 255, np.nan, agreement).astype(float)
    fig, ax = plt.subplots(figsize=(6.2, 5.2))
    ax.imshow(show, cmap=ListedColormap(AGREE_COLORS), vmin=0, vmax=3, interpolation="nearest")
    ax.axis("off")
    ax.set_title("Agreement with EMSR927" + (f" (IoU {iou:.2f})" if iou == iou and iou is not None else ""), fontsize=10)
    ax.legend(handles=[Patch(color=AGREE_COLORS[1], label="both flood"), Patch(color=AGREE_COLORS[2], label="ours only"),
                       Patch(color=AGREE_COLORS[3], label="reference only"), Patch(color=AGREE_COLORS[0], label="both dry")],
              loc="lower center", ncol=4, fontsize=7, frameon=False, bbox_to_anchor=(0.5, -0.08))
    return fig


def fig_failures(after_vv: np.ndarray, agreement: np.ndarray, k: int = 3, window: int = 96):
    """F4: crops around the k biggest disagreement blobs (ours-only or reference-only).
    Each crop shows the radar image and the agreement colours, so the report can
    explain a failure (shadow? debris? edge?) with evidence."""
    from scipy import ndimage
    plt = _plt()
    from matplotlib.colors import ListedColormap
    err = (agreement == 2) | (agreement == 3)
    labels, n = ndimage.label(err)
    h, w = err.shape
    centres = []
    if n:
        sizes = np.bincount(labels.ravel())[1:]
        for lab in np.argsort(sizes)[::-1][:k]:
            cy, cx = ndimage.center_of_mass(labels == lab + 1)
            centres.append((int(cy), int(cx), int(sizes[lab])))
    cols = max(1, len(centres))
    fig, ax = plt.subplots(2, cols, figsize=(3.4 * cols, 6.4), squeeze=False)
    for j in range(cols):
        if j < len(centres):
            cy, cx, sz = centres[j]
            y0 = int(np.clip(cy - window // 2, 0, max(h - window, 0))); x0 = int(np.clip(cx - window // 2, 0, max(w - window, 0)))
            sl = (slice(y0, y0 + window), slice(x0, x0 + window))
            ax[0, j].imshow(_stretch(after_vv[sl]), cmap="gray")
            ax[0, j].set_title(f"error blob {j + 1} ({sz} px)", fontsize=8)
            ax[1, j].imshow(np.where(agreement[sl] == 255, np.nan, agreement[sl]).astype(float),
                            cmap=ListedColormap(AGREE_COLORS), vmin=0, vmax=3, interpolation="nearest")
        else:
            ax[0, j].text(0.5, 0.5, "no disagreement", ha="center"); 
        ax[0, j].axis("off"); ax[1, j].axis("off")
    fig.suptitle("Largest disagreements (top: radar after, bottom: agreement)", fontsize=9)
    return fig


def fig_shift(shift: Dict[str, object]):
    """F5: IoU as the reference is shifted by (dy, dx) pixels; a peak away from
    the centre means part of the disagreement is georeferencing, not the model."""
    plt = _plt()
    grid, m = shift["iou_grid"], shift["max_shift"]
    fig, ax = plt.subplots(figsize=(4.6, 4.2))
    im = ax.imshow(grid, cmap="magma", extent=(-m - .5, m + .5, m + .5, -m - .5))
    ax.set_xlabel("dx (pixels)"); ax.set_ylabel("dy (pixels)")
    ax.set_title(f"IoU vs reference shift (best {shift['best_shift_dy_dx']})", fontsize=9)
    fig.colorbar(im, ax=ax, fraction=0.046)
    return fig
